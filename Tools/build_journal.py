#!/usr/bin/env python3
"""Build docs/journal/journal.md and index.html from manifest + reports/*.md."""

from __future__ import annotations

import html
import json
import re
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parents[1]
JOURNAL = ROOT / "docs" / "journal"
MANIFEST_PATH = JOURNAL / "journal.manifest.json"
REPORTS_DIR = JOURNAL / "reports"
JOURNAL_MD_PATH = JOURNAL / "journal.md"
INDEX_MD_PATH = JOURNAL / "index.md"
INDEX_HTML_PATH = JOURNAL / "index.html"

MD_EXTENSIONS = ["tables", "fenced_code", "nl2br", "sane_lists"]


def load_manifest() -> dict:
    with MANIFEST_PATH.open(encoding="utf-8") as f:
        return json.load(f)


def load_report_body(filename: str) -> str:
    return (REPORTS_DIR / filename).read_text(encoding="utf-8")


def rewrite_image_paths_for_html(text: str) -> str:
    return text.replace("](../screenshots/", "](screenshots/")


def rewrite_image_paths_for_journal_md(text: str) -> str:
    return text.replace("](../screenshots/", "](screenshots/")


def strip_report_preamble(report_md: str) -> str:
    """Drop duplicate title/metadata block; section header comes from manifest in HTML."""
    lines = report_md.splitlines()
    if not lines or not lines[0].startswith("# "):
        return report_md

    out: list[str] = []
    skipped_front = True
    for line in lines[1:]:
        if skipped_front:
            if line.strip() == "---":
                skipped_front = False
            continue
        out.append(line)
    return "\n".join(out).lstrip("\n")


def md_to_html_fragment(text: str) -> str:
    converted = markdown.markdown(
        rewrite_image_paths_for_html(text),
        extensions=MD_EXTENSIONS,
    )
    return converted


def build_scenes_table_md(scenes: list[dict]) -> str:
    lines = [
        "## Unity scenes",
        "",
        "| Scene | Experiment | Runners | Notes |",
        "|-------|------------|---------|-------|",
    ]
    for scene in scenes:
        notes = scene.get("formerly", "")
        if notes:
            notes = f"Renamed from `{notes}`"
        lines.append(
            f"| `{scene['path']}` | {scene['experiment']} | {scene['runners']} | {notes} |"
        )
    lines.append("")
    return "\n".join(lines)


def build_index_table_md(reports: list[dict]) -> str:
    lines = [
        "## Report index",
        "",
        "| Date | Experiment | Status | Unity scene | Report |",
        "|------|------------|--------|-------------|--------|",
    ]
    for report in reports:
        exp = f"{report['experiment_id']} — {report['title']}"
        report_file = report["file"]
        section_id = report["section_id"]
        lines.append(
            f"| {report['date']} | {exp} | {report['status']} | `{report['unity_scene']}` | "
            f"[Markdown](reports/{report_file}) · [HTML](index.html#{section_id}) |"
        )
    lines.append("")
    return "\n".join(lines)


def build_journal_md(manifest: dict, reports: list[dict]) -> str:
    parts = [
        f"# {manifest['title']}",
        "",
        manifest.get("subtitle", "Assembled from `reports/*.md`. Edit reports, then run `python Tools/build_journal.py`."),
        "",
        "_Generated by `Tools/build_journal.py`. Do not hand-edit; edit `reports/*.md` or `journal.manifest.json` instead._",
        "",
        build_scenes_table_md(manifest.get("scenes", [])),
        build_index_table_md(reports),
        "---",
        "",
    ]

    for report in reports:
        body = rewrite_image_paths_for_journal_md(load_report_body(report["file"]))
        parts.extend(
            [
                f"<!-- report: {report['section_id']} -->",
                f"<a id=\"{report['section_id']}\"></a>",
                "",
                body.rstrip(),
                "",
                "---",
                "",
            ]
        )

    return "\n".join(parts).rstrip() + "\n"


def build_index_md(manifest: dict, reports: list[dict]) -> str:
    parts = [
        "# Experiment Journal Index",
        "",
        build_scenes_table_md(manifest.get("scenes", [])),
        build_index_table_md(reports),
        "**Browse all reports:** [journal.md](journal.md) (full markdown) · [index.html](index.html) (mobile-friendly)",
        "",
    ]
    return "\n".join(parts)


def build_nav_html(reports: list[dict]) -> str:
    items = []
    for report in reports:
        label = f"{report['date']} · {report['experiment_id']} {report['title']}"
        items.append(
            f'          <li><a href="#{html.escape(report["section_id"])}">{html.escape(label)}</a></li>'
        )
    return "\n".join(items)


def build_section_html(report: dict) -> str:
    body_md = strip_report_preamble(load_report_body(report["file"]))
    body_html = md_to_html_fragment(body_md)
    verdict = report.get("verdict") or {}
    verdict_class = html.escape(verdict.get("class", ""))
    verdict_label = html.escape(verdict.get("label", ""))
    verdict_html = ""
    if verdict_class and verdict_label:
        verdict_html = f'\n        <div class="verdict-{verdict_class}">{verdict_label}</div>\n'

    return f"""      <section id="{html.escape(report["section_id"])}">
        <h2>{html.escape(report["experiment_id"])} — {html.escape(report["title"])}</h2>
        <div class="meta">
          <strong>Date:</strong> {html.escape(report["date"])} &nbsp;|&nbsp;
          <strong>ID:</strong> {html.escape(report["experiment_id"])} &nbsp;|&nbsp;
          <strong>Status:</strong> {html.escape(report["status"])} &nbsp;|&nbsp;
          <strong>Scene:</strong> <code>{html.escape(report["unity_scene"])}</code>
        </div>
{verdict_html}        <div class="report-body">
{body_html}
        </div>
        <p class="report-link">
          <a href="reports/{html.escape(report["file"])}">Source markdown</a>
        </p>
      </section>"""


def build_scenes_section_html(scenes: list[dict]) -> str:
    rows = []
    for scene in scenes:
        note = ""
        if scene.get("formerly"):
            note = f"Renamed from <code>{html.escape(scene['formerly'])}</code>"
        rows.append(
            "<tr>"
            f"<td><code>{html.escape(scene['path'])}</code></td>"
            f"<td>{html.escape(scene['experiment'])}</td>"
            f"<td>{html.escape(scene['runners'])}</td>"
            f"<td>{note}</td>"
            "</tr>"
        )
    rows_html = "\n          ".join(rows)
    return f"""      <section id="unity-scenes">
        <h2>Unity scenes</h2>
        <p>Preset scenes under <code>Assets/Scenes/</code> (formerly a single <code>SampleScene.unity</code>).</p>
        <table>
          <tr><th>Scene</th><th>Experiment</th><th>Runners</th><th>Notes</th></tr>
          {rows_html}
        </table>
      </section>"""


