def build_index_html(manifest: dict, reports: list[dict]) -> str:
    sections = "\n\n".join(build_section_html(r) for r in reports)
    scenes_section = build_scenes_section_html(manifest.get("scenes", []))
    return HTML_TEMPLATE.format(
        title=html.escape(manifest["title"]),
        subtitle=html.escape(manifest.get("subtitle", "")),
        nav=build_nav_html(reports),
        scenes_section=scenes_section,
        sections=sections,
    )


def sorted_reports(manifest: dict) -> list[dict]:
    return sorted(manifest["reports"], key=lambda r: r.get("sort_order", 999))


def main() -> None:
    manifest = load_manifest()
    reports = sorted_reports(manifest)

    JOURNAL_MD_PATH.write_text(build_journal_md(manifest, reports), encoding="utf-8")
    INDEX_MD_PATH.write_text(build_index_md(manifest, reports), encoding="utf-8")
    INDEX_HTML_PATH.write_text(build_index_html(manifest, reports), encoding="utf-8")

    print(f"Wrote {JOURNAL_MD_PATH.relative_to(ROOT)}")
    print(f"Wrote {INDEX_MD_PATH.relative_to(ROOT)}")
    print(f"Wrote {INDEX_HTML_PATH.relative_to(ROOT)}")
    print(f"Reports: {len(reports)}")


if __name__ == "__main__":
    main()
